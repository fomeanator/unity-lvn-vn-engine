using Lvn.Content;
using NUnit.Framework;

namespace Lvn.Tests
{
    /// <summary>
    /// СЛАБОЕ УСТРОЙСТВО НЕ ОБЕЩАЕТ СЕБЕ БОЛЬШЕ, ЧЕМ У НЕГО ЕСТЬ.
    ///
    /// <para>Условие взято с живого прогона 06.09. Телефон (эмулятор) на
    /// 976 МБ: движок объявил бюджет спрайт-кэша 162 МБ — шестую часть ПАМЯТИ
    /// УСТРОЙСТВА, — тогда как свободными в системе оставались 80 МБ, а сам
    /// процесс дорос до 292 МБ при 37 МБ оставшихся. Игра открылась, но
    /// стояла в шаге от того, чтобы её сняли; Android слал LOW_MEMORY ещё до
    /// первого кадра.</para>
    ///
    /// <para>Вся память устройства нам не принадлежит: рядом живут система,
    /// магазин, лаунчер. Поэтому решать должно МЕНЬШЕЕ из двух — доля
    /// устройства и половина планки, которую Android обещает приложению.</para>
    /// </summary>
    public class WeakDeviceBudgetTests
    {
        private const long МБ = 1L << 20;

        [Test]
        public void ПланкаПриложенияПобеждаетПамятьУстройства()
        {
            // Тот самый случай: гигабайт устройства, планка приложения 128 МБ.
            long бюджет = ContentLoader.BudgetFor(976, 128);
            TestContext.WriteLine($"976 МБ устройства, планка 128 МБ → {бюджет / МБ} МБ");
            Assert.LessOrEqual(бюджет, 64 * МБ,
                "бюджет больше половины обещанного приложению — кэш начнёт соревноваться "
              + "с текстурами сцены и приведёт к тому же LOW_MEMORY");
        }

        [Test]
        public void ПолНеПроталкиваетНевыполнимыйБюджет()
        {
            // Пол в 96 МБ — правило для устройства, где столько ЕСТЬ. При
            // маленькой планке он обязан опуститься вместе с ней.
            Assert.LessOrEqual(ContentLoader.BudgetFor(512, 64), 32 * МБ,
                "пол протолкнул бюджет выше планки приложения");
        }

        [Test]
        public void НаСильномУстройствеПравилоПрежнее()
        {
            // Планка известна и велика — работает доля устройства.
            Assert.AreEqual(1024 * МБ / 6, ContentLoader.BudgetFor(1024, 512),
                "на устройстве с запасом бюджет должен считаться прежней долей");
            // И потолок остаётся потолком.
            Assert.AreEqual(384 * МБ, ContentLoader.BudgetFor(8192, 1024),
                "потолок бюджета пробит");
        }

        [Test]
        public void ПланкаНеизвестна_РешаетПрежнееПравило()
        {
            Assert.AreEqual(96 * МБ, ContentLoader.BudgetFor(256, 0),
                "без планки должно работать прежнее правило с полом 96 МБ");
        }

        /// <summary>
        /// РАСПАКОВКА ОСТАВЛЯЕТ ЯДРО КАДРУ.
        ///
        /// <para>«Лагает во время загрузки ассетов» на двухъядерном устройстве
        /// — это не декод (он давно вне главного потока), а его ШИРИНА: три
        /// распаковки разом на двух ядрах означают, что главный поток стоит в
        /// очереди за собственный кадр.</para>
        /// </summary>
        [Test]
        public void ШиринаРаспаковкиНеБольшеЧислаЯдерМинусКадр()
        {
            int ядер = Lvn.LvnDeviceProfile.Cores;
            int ширина = LvnLanes.Decoder.Width;
            TestContext.WriteLine($"ядер {ядер}, полос распаковки {ширина}");
            Assert.GreaterOrEqual(ширина, 1, "распаковка совсем остановлена");
            Assert.LessOrEqual(ширина, 3, "полос больше прежнего предела");
            if (ядер > 0)
                Assert.LessOrEqual(ширина, System.Math.Max(1, ядер - 1),
                    "распаковка забрала все ядра — кадру не осталось ни одного");
        }
    }
}
