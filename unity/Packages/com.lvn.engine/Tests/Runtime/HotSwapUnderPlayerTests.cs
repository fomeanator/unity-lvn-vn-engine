using System;
using System.Collections;
using Lvn;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.TestTools;
using UnityEngine.UIElements;

namespace Lvn.Tests
{
    /// <summary>
    /// ПРАВКА ГЛАВЫ ПОД ЧИТАЮЩИМ НЕ ВЫБРАСЫВАЕТ ЕГО ИЗ ИСТОРИИ.
    ///
    /// <para>Условие, ради которого живая раздача и существует: автор замечает
    /// опечатку в вышедшей главе и правит её, пока эту главу читают. Игрок в
    /// этот момент на середине. Он не должен ни увидеть свою главу с начала, ни
    /// остаться со старым текстом до перезапуска приложения.</para>
    ///
    /// <para>У правки две породы, и обходятся с ними по-разному. Переписанная
    /// реплика структуру не меняет — курсор остаётся на месте, меняется текст.
    /// Добавленная или убранная команда двигает всё, что за ней: там честнее
    /// перезапустить главу, чем делать вид, что игрок стоит там же.</para>
    /// </summary>
    public class HotSwapUnderPlayerTests
    {
        private GameObject _go;
        private PanelSettings _panel;
        private VnStage _stage;

        private const string Редакция1 = @"{""scene"":""глава"",""script"":[
            {""op"":""say"",""text"":""первая реплика""},
            {""op"":""say"",""text"":""вторая реплика с апечаткой""},
            {""op"":""say"",""text"":""третья реплика""},
            {""op"":""say"",""text"":""четвёртая реплика""}]}";

        // Та же структура, исправлен текст той реплики, на которой стоит игрок.
        private const string Редакция2 = @"{""scene"":""глава"",""script"":[
            {""op"":""say"",""text"":""первая реплика""},
            {""op"":""say"",""text"":""вторая реплика без опечатки""},
            {""op"":""say"",""text"":""третья реплика, переписанная""},
            {""op"":""say"",""text"":""четвёртая реплика""}]}";

        // Структурная правка: автор вставил реплику в середину.
        private const string Редакция3 = @"{""scene"":""глава"",""script"":[
            {""op"":""say"",""text"":""первая реплика""},
            {""op"":""say"",""text"":""вставленная реплика""},
            {""op"":""say"",""text"":""вторая реплика без опечатки""},
            {""op"":""say"",""text"":""третья реплика""},
            {""op"":""say"",""text"":""четвёртая реплика""}]}";

        [UnitySetUp]
        public IEnumerator Стенд()
        {
            _stage = TestStage.Panel("hotswap-stage", out _go, out _panel);
            yield return null;
        }

        [UnityTearDown]
        public IEnumerator Уборка()
        {
            LvnScreenDirector.Current.ShowChromeAll();
            // Сцену снимаем ДО сноса объектов: отложенные вызовы расписания
            // иначе всплывают в журнале следующего теста (ловил в эту же ночь).
            _stage?.ClearStage();
            _stage = null;
            yield return null;
            if (_go != null) UnityEngine.Object.Destroy(_go);
            if (_panel != null) UnityEngine.Object.Destroy(_panel);
            yield return null;
        }

        private static IEnumerator Ждём(Func<bool> готово, float секунд)
        {
            float срок = Time.realtimeSinceStartup + секунд;
            while (Time.realtimeSinceStartup < срок && !готово()) yield return null;
        }

        private bool ВИстории(string текст)
        {
            foreach (var строка in _stage.Backlog)
                if (строка.text == текст) return true;
            return false;
        }

        // ЧТО ЧИТАЕТ ИГРОК — спрашиваем у ИСТОРИИ и у следующего шага, а не у
        // подписи на экране. Подпись в безголовом прогоне отстаёт (текст
        // печатается по кадрам, которых здесь нет): замер 06.09 показал на
        // ней «первую реплику» там, где игрок стоял на второй, — и чуть не
        // объявил дефектом движка отставание собственной мерки.
        private string НаЭкране() => _go != null
            ? _go.GetComponent<UIDocument>()?.rootVisualElement?.Q<Label>("vn-body")?.text
            : null;

        // Последняя реплика, которую игрок ДЕЙСТВИТЕЛЬНО прочитал.
        private string Последняя()
        {
            string last = null;
            foreach (var строка in _stage.Backlog) last = строка.text;
            return last;
        }

        [UnityTest]
        public IEnumerator ИсправленнаяОпечаткаНеСбрасываетГлавуВНачало()
        {
            _stage.Play(Редакция1);
            yield return null;
            _stage.Player.Advance();          // стоим на второй реплике
            yield return Ждём(() => ВИстории("вторая реплика с апечаткой"), 5f);
            int былиНа = _stage.Player.Index;
            Assert.IsTrue(ВИстории("вторая реплика с апечаткой"), "стенд: не дошли до правимой реплики");

            bool наМесте = _stage.TryHotSwap(Редакция2);
            yield return null;
            TestContext.WriteLine($"правка текста: подхвачена на месте={наМесте}, "
                                + $"позиция {былиНа} → {_stage.Player.Index}");

            Assert.IsTrue(наМесте,
                "переписанная реплика не подхватилась на лету — игрок останется со старым текстом "
              + "до перезапуска приложения");
            Assert.AreEqual(былиНа, _stage.Player.Index,
                "правка текста сдвинула курсор — игрок читает не ту реплику, на которой стоял");
            // ДАЛЬШЕ ИГРА ИДЁТ ПО НОВОЙ РЕДАКЦИИ, и с того же места: следующая
            // реплика — переписанная третья, а не «первая» и не «вторая».
            _stage.Player.Advance();
            yield return Ждём(() => ВИстории("третья реплика, переписанная"), 5f);
            TestContext.WriteLine($"после правки прочитано дальше: «{Последняя()}»");
            Assert.IsTrue(ВИстории("третья реплика, переписанная"),
                "после правки игра не пошла дальше по новой редакции");
            Assert.IsFalse(ВИстории("первая реплика") && Последняя() == "первая реплика",
                "игрока отбросило назад по тексту");
        }

        // Те же четыре реплики, но глава РАЗМЕЧЕНА: перед каждой сценой метка.
        private const string РазмеченнаяA = @"{""scene"":""глава"",""script"":[
            {""op"":""label"",""id"":""вступление""},
            {""op"":""say"",""text"":""первая реплика""},
            {""op"":""label"",""id"":""разговор""},
            {""op"":""say"",""text"":""вторая реплика без опечатки""},
            {""op"":""say"",""text"":""третья реплика""}]}";

        private const string РазмеченнаяБ = @"{""scene"":""глава"",""script"":[
            {""op"":""label"",""id"":""вступление""},
            {""op"":""say"",""text"":""первая реплика""},
            {""op"":""say"",""text"":""вставленная реплика""},
            {""op"":""label"",""id"":""разговор""},
            {""op"":""say"",""text"":""вторая реплика без опечатки""},
            {""op"":""say"",""text"":""третья реплика""}]}";

        [UnityTest]
        public IEnumerator СтруктурнаяПравкаБезМетокСдвигаетЧитающего()
        {
            _stage.Play(Редакция2);
            yield return null;
            _stage.Player.Advance();
            yield return Ждём(() => ВИстории("вторая реплика без опечатки"), 5f);

            int былиНа = _stage.Player.Index;
            bool наМесте = _stage.TryHotSwap(Редакция3);
            yield return null;
            TestContext.WriteLine($"вставлена реплика ВЫШЕ игрока: подхвачено={наМесте}, "
                                + $"позиция {былиНа} → {_stage.Player.Index}, на экране «{НаЭкране()}»");

            // ЗАМЕР ФИКСИРУЕТ НЫНЕШНЕЕ ПОВЕДЕНИЕ, а не желаемое. Курсор
            // пересаживается ПО ЯКОРЮ — ближайшей метке и шагам от неё; в
            // главе без единой метки якорю не за что зацепиться, и номер
            // команды остаётся прежним, хотя текст под ним уже другой.
            // Игрок, стоявший на второй реплике, оказывается на первой.
            //
            // Это та же граница, что и у сейва после правки (см. канон,
            // «главу укоротили»): без меток движок не умеет держать место.
            // Соседняя проверка ниже показывает, что С МЕТКАМИ всё работает.
            Assert.IsTrue(наМесте, "структурная правка не подхватилась вовсе");
            _stage.Player.Advance();
            yield return Ждём(() => Последняя() != "вторая реплика без опечатки", 5f);
            TestContext.WriteLine($"после вставки следующей прочиталась: «{Последняя()}»");
            Assert.AreNotEqual("вставленная реплика", Последняя(),
                "игрок прочитал реплику, вставленную ВЫШЕ него, — курсор поехал по номеру команды");
        }

        [UnityTest]
        public IEnumerator ВРазмеченнойГлавеСтруктурнаяПравкаНеТрогаетМестоЧитающего()
        {
            _stage.Play(РазмеченнаяA);
            yield return null;
            _stage.Player.Advance();
            yield return Ждём(() => ВИстории("вторая реплика без опечатки"), 5f);
            Assert.IsTrue(ВИстории("вторая реплика без опечатки"), "стенд: не дошли до нужной реплики");

            int былиНа = _stage.Player.Index;
            string былоНаЭкране = НаЭкране();
            bool наМесте = _stage.TryHotSwap(РазмеченнаяБ);
            yield return null;
            TestContext.WriteLine($"размеченная глава, вставка ВЫШЕ игрока: подхвачено={наМесте}, "
                                + $"позиция {былиНа} → {_stage.Player.Index}, "
                                + $"на экране было «{былоНаЭкране}», стало «{НаЭкране()}»");

            Assert.IsTrue(наМесте, "правка размеченной главы не подхватилась");
            _stage.Player.Advance();
            yield return Ждём(() => ВИстории("третья реплика"), 5f);
            TestContext.WriteLine($"после правки прочитано дальше: «{Последняя()}»");
            Assert.IsTrue(ВИстории("третья реплика"),
                "после правки история не пошла дальше со своего места");
            Assert.IsFalse(ВИстории("вставленная реплика"),
                "в историю игрока попала реплика, вставленная ВЫШЕ него");
        }
    }
}
