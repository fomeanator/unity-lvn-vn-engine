using System.Collections.Generic;
using Lvn;
using Lvn.Content;
using Lvn.UI;
using NUnit.Framework;
using UnityEngine;

namespace Lvn.Tests
{
    /// <summary>
    /// НАДЕТОЕ ПЕРЕЕЗЖАЕТ ВМЕСТЕ С ИГРОКОМ — И ГРАНИЦА ЭТОГО НАЗВАНА.
    ///
    /// <para>Условие: игрок купил наряд и надел его на телефоне, потом вошёл
    /// своим аккаунтом на планшете. Покупка у него на сервере (инвентарь
    /// кошелька), а вот НАДЕТОЕ живёт в книжке устройства — то есть на
    /// планшете его нет. Единственная дорога надетого через сеть — переменные
    /// истории: ось гардероба может объявить свою (<c>var</c> в манифесте), и
    /// тогда выбор уезжает в состояние новеллы, которое хранится на сервере.
    /// </para>
    ///
    /// <para>Значит обещание «наряд переезжает» держится РОВНО ДЛЯ ОСЕЙ С
    /// ПЕРЕМЕННОЙ. Ось без неё — гардеробная, локальная: она переживёт
    /// перезапуск игры, но не переезд на другое устройство. Это не дефект, а
    /// цена простоты, и записана она здесь, чтобы автор знал её до того, как
    /// игрок пожалуется.</para>
    /// </summary>
    public class WardrobeTravelTests
    {
        private const string Героиня = "стенд-героиня";
        private string _владелец;

        private static Dictionary<string, LvnWardrobeSlot> Оси() => new Dictionary<string, LvnWardrobeSlot>
        {
            ["платье"] = new LvnWardrobeSlot { name = "Платье", storyVar = "Гардероб.платье" },
            ["брошь"] = new LvnWardrobeSlot { name = "Брошь" },   // без переменной — гардеробная
        };

        [SetUp]
        public void Стенд()
        {
            _владелец = LvnKeep.Owner;
            LvnWardrobe.Clear(Героиня);
        }

        [TearDown]
        public void Уборка()
        {
            LvnWardrobe.Clear(Героиня);
            LvnKeep.NoteOwner(_владелец ?? "");
        }

        [Test]
        public void НадетоеПереживаетПерезапускИПереездОсьюСПеременной()
        {
            // ── надели на телефоне ──────────────────────────────────────────
            LvnWardrobe.Equip(Героиня, "платье", "бальное");
            LvnWardrobe.Equip(Героиня, "брошь", "рубиновая");
            Assert.AreEqual("бальное", LvnWardrobe.Equipped(Героиня)["платье"]);
            Assert.AreEqual("рубиновая", LvnWardrobe.Equipped(Героиня)["брошь"]);

            // ── «закрыли и открыли игру»: книжка устройства та же ───────────
            var послеПерезапуска = LvnWardrobe.Equipped(Героиня);
            Assert.AreEqual("бальное", послеПерезапуска["платье"], "наряд не пережил перезапуск игры");
            Assert.AreEqual("рубиновая", послеПерезапуска["брошь"], "брошь не пережила перезапуск игры");

            // ── что уезжает на сервер: переменные истории ───────────────────
            var переменные = new Dictionary<string, string>();
            LvnWardrobeSync.ToVars(Героиня, Оси(), (имя, знач) => переменные[имя] = знач);
            TestContext.WriteLine("в состояние новеллы уехало: "
                                + (переменные.Count == 0 ? "ничего" : string.Join(", ", переменные)));

            Assert.IsTrue(переменные.ContainsKey("Гардероб.платье"),
                "ось с переменной не положила выбор в состояние — на другом устройстве наряда не будет");
            Assert.AreEqual("бальное", переменные["Гардероб.платье"]);
            Assert.AreEqual(1, переменные.Count,
                "ось БЕЗ переменной уехала в состояние — значит правило «var решает» больше не действует");

            // ── переезд: другое устройство, тот же игрок ────────────────────
            // Другой владелец ключей = чистая книжка (это правило проверено
            // отдельно, «чужое прохождение не достаётся второму игроку»).
            LvnKeep.NoteOwner("другое-устройство-" + Героиня);
            LvnWardrobe.Clear(Героиня);
            Assert.AreEqual(0, LvnWardrobe.Equipped(Героиня).Count, "стенд: книжка не чистая, переезд не воспроизвёлся");

            // Состояние новеллы приехало с сервера — гардероб восстанавливается из него.
            LvnWardrobeSync.FromVars(Героиня, Оси(),
                имя => переменные.TryGetValue(имя, out var v) ? v : null);
            var наПланшете = LvnWardrobe.Equipped(Героиня);
            TestContext.WriteLine($"после переезда надето: {string.Join(", ", наПланшете)}");

            Assert.AreEqual("бальное", наПланшете.TryGetValue("платье", out var п) ? п : null,
                "наряд с переменной не доехал до второго устройства");
            Assert.IsFalse(наПланшете.ContainsKey("брошь"),
                "ГРАНИЦА ИЗМЕНИЛАСЬ: гардеробная ось (без var) доехала до второго устройства — "
              + "если это сделано намеренно, перепишите проверку и запись в каноне");
        }
    }
}
