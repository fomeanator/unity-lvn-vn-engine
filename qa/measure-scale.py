#!/usr/bin/env python3
"""Замер эталонной шкалы цветового тракта (content/hdr-test/scale.lvns).

Смысл в том, чтобы про картинку можно было говорить ЧИСЛАМИ. «Стало хуже» —
не наблюдение, а впечатление; «шар с эмиссией 8 перестал отличаться от шара с
эмиссией 2» — наблюдение, и по нему сразу видно, где искать.

Читает два кадра одной сцены — снятый БЕЗ тональной кривой (технический
исходник) и с ней (визуальный эталон) — и печатает яркости зон.

Что проверяется:
  · шкала эмиссии    — растёт ли яркость с силой свечения и не упирается ли
                       она в потолок раньше времени;
  · серая шкала      — сохраняет ли кривая различимость светов;
  · ореол            — шире ли свечение вокруг яркого, чем вокруг тусклого;
  · фон              — не изменился ли он от посторонних источников.

Запуск: python3 qa/measure-scale.py <кадр-off.png> <кадр-tone.png>
"""
import sys
from PIL import Image

# Зоны в ДОЛЯХ кадра, а не в пикселях: разрешение съёмки может меняться, а
# композиция сцены зафиксирована — значит доли остаются верными.
ZONES = [
    # (имя,          x0,    y0,    x1,    y1) — доли кадра, снято с эталона.
    # Шары: только ободок и ореол, центр тёмный (сфера не освещена спереди).
    ("эмиссия 0",   0.14, 0.40, 0.21, 0.47),
    ("эмиссия 1",   0.31, 0.40, 0.37, 0.47),
    ("эмиссия 2",   0.47, 0.40, 0.53, 0.47),
    ("эмиссия 4",   0.63, 0.40, 0.69, 0.47),
    ("эмиссия 8",   0.80, 0.40, 0.86, 0.47),
    # Плитки: середина каждой, без краёв и без стыков.
    ("серый 0.05",  0.20, 0.50, 0.27, 0.55),
    ("серый 0.23",  0.33, 0.50, 0.39, 0.55),
    ("серый 0.46",  0.47, 0.50, 0.53, 0.55),
    ("серый 0.71",  0.60, 0.50, 0.66, 0.55),
    ("серый 0.94",  0.74, 0.50, 0.80, 0.55),
    # Фон: небо над шкалой и пол под ней — сюда не должен доставать никто.
    ("фон верх",    0.40, 0.06, 0.60, 0.14),
    ("фон низ",     0.05, 0.88, 0.20, 0.96),
]


# Центры образцов шкалы эмиссии и радиус их тела — в долях ширины кадра.
# Нужны, чтобы мерить ОРЕОЛ отдельно от самого шара: яркость тела говорит,
# сколько света рождается, а ореол — сколько его расходится вокруг. Это разные
# величины, и ломаются они по-разному: потолок в шейдере гасит первую, а
# неверный порог свечения — вторую.
SAMPLES = [
    ("ореол 0", 0.170), ("ореол 1", 0.337), ("ореол 2", 0.500),
    ("ореол 4", 0.663), ("ореол 8", 0.828),
]
SAMPLE_Y = 0.430      # высота ряда шаров
SAMPLE_R = 0.043      # радиус тела шара (снято с эталона: 39 px из 900)


def ring_mean(img, cx, cy, r_in, r_out):
    """Яркость КОЛЬЦА вокруг точки: тело образца исключено.

    Прямоугольная зона тут не годится — она неизбежно захватит либо часть
    шара, либо соседа. Кольцо же смотрит ровно туда, куда уходит свет.
    """
    w, h = img.size
    px = img.load()
    x0, y0 = cx * w, cy * h
    ri, ro = r_in * w, r_out * w
    n = 0
    s = 0.0
    for y in range(int(y0 - ro), int(y0 + ro) + 1):
        if y < 0 or y >= h:
            continue
        for x in range(int(x0 - ro), int(x0 + ro) + 1):
            if x < 0 or x >= w:
                continue
            d = ((x - x0) ** 2 + (y - y0) ** 2) ** 0.5
            if d < ri or d > ro:
                continue
            r, g, b = px[x, y][:3]
            s += 0.2126 * r + 0.7152 * g + 0.0722 * b
            n += 1
    return s / max(1, n)


def zone_mean(img, z):
    w, h = img.size
    px = img.load()
    x0, y0 = int(z[1] * w), int(z[2] * h)
    x1, y1 = int(z[3] * w), int(z[4] * h)
    n = 0
    s = 0.0
    for y in range(y0, y1, 2):
        for x in range(x0, x1, 2):
            r, g, b = px[x, y][:3]
            # Воспринимаемая яркость: глаз видит зелёный в шесть раз лучше
            # синего, и среднее по каналам врало бы в пользу синевы ночи.
            s += 0.2126 * r + 0.7152 * g + 0.0722 * b
            n += 1
    return s / max(1, n)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    a = Image.open(sys.argv[1]).convert("RGB")
    b = Image.open(sys.argv[2]).convert("RGB")

    print(f"{'зона':<14}{'без кривой':>12}{'с кривой':>12}{'разница':>10}")
    print("─" * 48)
    vals_a, vals_b = {}, {}
    for z in ZONES:
        ma, mb = zone_mean(a, z), zone_mean(b, z)
        vals_a[z[0]], vals_b[z[0]] = ma, mb
        print(f"{z[0]:<14}{ma:>12.1f}{mb:>12.1f}{mb - ma:>+10.1f}")

    print()
    # Главная проверка: шкала эмиссии обязана РАСТИ. Если соседние ступени
    # совпали, значит яркость упирается в потолок — либо шейдер обрезает её
    # сам, либо буфер не хранит значений выше белого.
    steps = ["эмиссия 0", "эмиссия 1", "эмиссия 2", "эмиссия 4", "эмиссия 8"]
    ladder = [vals_b[s] for s in steps]

    # ДОПУСК. Между видеокартами (и между прогонами с разным сглаживанием)
    # яркость гуляет на доли процента, и абсолютный порог заставлял бы тест
    # мигать без всякой причины. Считаем в долях от разброса самой шкалы:
    # так проверка не зависит ни от разрешения, ни от экспозиции сцены.
    span = max(ladder) - min(ladder)
    tol = max(1.5, span * 0.03)

    # НАСЫЩЕНИЕ ТЕЛА — не поломка. Само пятно рано или поздно упирается в
    # белое: в этом и смысл кривой. Важно отличать его от ПОТОЛКА в шейдере,
    # где яркость не росла вообще ни на одной ступени.
    ceiling = 0.94 * 255
    flat, saturated = [], []
    for i in range(len(ladder) - 1):
        if ladder[i + 1] - ladder[i] >= tol:
            continue
        (saturated if ladder[i] > ceiling * 0.75 else flat).append(steps[i + 1])

    if flat:
        print("  ✗ шкала эмиссии не растёт на ступенях: " + ", ".join(flat))
        print("    (яркость упирается в потолок — ищите saturate/fixed/LDR)")
    else:
        print(f"  ✓ шкала эмиссии растёт (допуск {tol:.1f})")
    if saturated:
        print("  · тело насыщено на ступенях: " + ", ".join(saturated) +
              " — это работа кривой, следите за ореолом")

    # Кривая обязана сохранять различимость СВЕТОВ: если два самых светлых
    # пятна слились, света срезаны, а не сжаты.
    d = vals_b["серый 0.94"] - vals_b["серый 0.71"]
    print(f"  {'✓' if d > 3 else '✗'} света различимы: разница верхних пятен {d:+.1f}")

    # ОРЕОЛ — отдельно от тела. Свечение должно РАСХОДИТЬСЯ тем шире, чем
    # ярче источник; если ореол одинаков у двойки и восьмёрки, значит порог
    # свечения срабатывает раньше, чем задумано, и ловит всё подряд.
    print()
    print(f"{'ореол':<14}{'без кривой':>12}{'с кривой':>12}{'разница':>10}")
    print("─" * 48)
    halo_b = []
    for name, cx in SAMPLES:
        # Кольцо ВПЛОТНУЮ к телу: свечение спадает быстро, и уже на двух
        # радиусах от центра его не остаётся — там меряется чистый фон.
        ha = ring_mean(a, cx, SAMPLE_Y, SAMPLE_R * 1.0, SAMPLE_R * 1.45)
        hb = ring_mean(b, cx, SAMPLE_Y, SAMPLE_R * 1.0, SAMPLE_R * 1.45)
        halo_b.append(hb)
        print(f"{name:<14}{ha:>12.1f}{hb:>12.1f}{hb - ha:>+10.1f}")

    # Тусклые образцы светиться почти не должны: порог выше белого на то и
    # нужен, чтобы ореол доставался источникам, а не всему светлому.
    quiet = halo_b[1] - halo_b[0]
    # Ореол — ОСНОВНАЯ метрика: в отличие от тела, он не насыщается и растёт
    # ровно столько, сколько растёт энергия источника.
    hspan = max(halo_b) - min(halo_b)
    htol = max(0.8, hspan * 0.05)
    grows = [i for i in range(2, len(halo_b)) if halo_b[i] - halo_b[i - 1] < htol]
    print()
    print(f"  {'✓' if quiet < 8 else '✗'} слабые почти не светятся: "
          f"ореол единицы выше нуля на {quiet:+.1f}")
    if grows:
        print("  ✗ ореол не растёт на ступенях: " +
              ", ".join(SAMPLES[i][0] for i in grows))
    else:
        print(f"  ✓ ореол растёт от ступени к ступени (допуск {htol:.1f})")

    return 0


if __name__ == "__main__":
    sys.exit(main())
